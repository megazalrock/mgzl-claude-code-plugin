/**
 * 目次（index.md / SessionStart 注入）に載せるタイトルを、表示時にだけ短縮する置換表。
 *
 * 抽出されるタイトルには「〜ときに参照する」「〜を確認したいときに使う」のような、
 * 記憶の中身を足さない定型句が多く含まれ、SessionStart の注入量を押し上げている（issue #65）。
 * 保存済みの title（frontmatter）は書き換えない。dedup.ts の重複検出が保存済み title をそのまま比較しており、
 * その閾値は現在の title の分布で調整されているため、保存時に短縮すると閾値の前提が崩れる。
 *
 * 規則は上から順に適用する。前段の出力（「時→」「時の」など）を後段が前提にしているので順序を入れ替えないこと。
 * 切り詰め（文字数での打ち切り）は意味が壊れるため行わない。
 */
type Rule = {
  id: string;
  pattern: RegExp;
  replace: string;
};

// 「確認したい」「知りたい」等、情報そのものを指すだけで意味を足さない動詞句。
// 「把握する」は「ログを分析して〜を把握する」のように前段の動詞とつながる例があり、消すと「分析して」が宙に浮くので含めない
const WANT_VERB = "(?:(?:確認|調査)(?:する|したい)|知りたい|調べ(?:る|たい)|聞かれた)";
// 場面の区切りとみなす語。「実際に使う」「同時に使う」を区切りと誤認して「実時→」「同時の」に壊さないよう、
// 際・時の直前が熟語の一部になる字のときは除外する
const TRIGGER = "(?:とき|(?<![実交国])際|(?<![同当即随常臨])時)に?";

const RULES: Rule[] = [
  {
    // 「Xの際に参照」「Xのときに使う」→「X時に参照」。後段の規則に「〜時」の形で渡すための正規化
    id: "B0-no-sai",
    pattern: /の(?:際|とき)に(?=参照|使|踏ま|守)/gu,
    replace: "時に",
  },
  {
    // 「Xを確認したいときに使う情報」→「X」。情報の中身が X そのものなので定型部分は丸ごと落とせる。
    // 「〜か確認したい」の「か」は疑問の意味を担うので残す
    id: "B1a-want-end",
    pattern: new RegExp(`(?:を|(か))${WANT_VERB}(?:とき|際)に?(?:使う|参照する)(?:情報)?$`, "u"),
    replace: "$1",
  },
  {
    // 「Xを確認したいときに使う、Y」「Xを調べたいときに使うissue情報」→「X→Y」
    id: "B1b-want-mid",
    pattern: new RegExp(`(?:を|(か))${WANT_VERB}(?:とき|際)に?(?:使う|参照する)、?(?=.)`, "u"),
    replace: "$1→",
  },
  {
    // 「〜ときに参照する、Y」「〜際に踏まえるべき、Y」→「〜時→Y」。場面と中身の区切りは → で残す
    id: "B2-trigger-comma",
    pattern: new RegExp(
      `${TRIGGER}(?:(?:参照|使用)する|使う|(?:必ず)?(?:踏まえるべき|守るべき)|参考にする|事前に把握しておくと役立つ)、`,
      "gu",
    ),
    replace: "時→",
  },
  {
    // 「〜ときに参照する挙動と対処」→「〜時の挙動と対処」（直後が名詞で読点が無い形）
    id: "B3-trigger-noun",
    pattern: new RegExp(
      `${TRIGGER}(?:(?:参照|使用)する|使う|(?:必ず)?(?:踏まえるべき|守るべき))(?=[^\\s、。）)」])`,
      "gu",
    ),
    replace: "時の",
  },
  {
    // 末尾・括弧閉じ直前の「〜際に参照する」「修正時に使う）」→「〜時」
    id: "B4-trigger-end",
    pattern: new RegExp(`${TRIGGER}(?:参照(?:する)?|使用する|使う)(?=$|[）)。])`, "gu"),
    replace: "時",
  },
];

/** 目次表示用に title の定型句を除く。定型句を含まない title はそのまま返す */
export function shortenTitle(title: string): string {
  return RULES.reduce((t, r) => t.replace(r.pattern, r.replace), title);
}
